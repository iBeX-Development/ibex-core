      this.assigned,
      this.requireEv,
      this.avatar,
      this.title,
      this.description,
      this.location,
      this.active,
      this.locationId});
  User.fromJson(Map<String, dynamic> json) {
    try {
      // ✅ Handle ID with null safety
      if (json.containsKey('id') && json['id'] != null) {
        var idValue = json['id'];
        if (idValue is String) {
          id = UserIdMapper().getIntId(idValue);
        } else if (idValue is int) {
          id = idValue;
        }
      }

      // ✅ Basic required fields
      firstName = json.containsKey('first_name') ? json['first_name'] : null;
      lastName = json.containsKey('last_name') ? json['last_name'] : null;
      email = json.containsKey('email') ? json['email'] : null;

      // ✅ Handle role
      if (json.containsKey('role') && json['role'] != null) {
        role = json['role'].toString();
      }

      // ✅ Handle roleId
      if (json.containsKey('role_id') && json['role_id'] != null) {
        var roleIdValue = json['role_id'];
        if (roleIdValue is String) {
          roleId = int.tryParse(roleIdValue);
        } else if (roleIdValue is int) {
          roleId = roleIdValue;
        }
      }

      // ✅ Handle phone
      if (json.containsKey('phone') && json['phone'] != null) {
        phone = json['phone'].toString();
      }

      // ✅ Optional string fields
      countryCode =
          json.containsKey('country_code') && json['country_code'] != null
              ? json['country_code']
              : null;
      password = json.containsKey('password') ? json['password'] : null;
      passwordConfirmation = json.containsKey('password_confirmation')
          ? json['password_confirmation']
          : null;
      type = json.containsKey('type') ? json['type'] : null;
      dob = json.containsKey('dob') ? json['dob'] : null;
      doj = json.containsKey('doj') ? json['doj'] : null;
      address = json.containsKey('address') ? json['address'] : null;
      city = json.containsKey('city') ? json['city'] : null;
      state = json.containsKey('state') ? json['state'] : null;
      country = json.containsKey('country') ? json['country'] : null;
      zip = json.containsKey('zip') ? json['zip'] : null;

      // ✅ Handle avatar/profile
      if (json.containsKey('avatar') && json['avatar'] != null) {
        var avatarValue = json['avatar'];
        if (avatarValue is String && avatarValue.isNotEmpty) {
          if (avatarValue.contains('-') && !avatarValue.startsWith('http')) {
            profile = '$activePictureUrl/$avatarValue';
          } else {
            profile = avatarValue;
          }
        }
      }
      avatar = profile;

      // ✅ CRITICAL FIX: Handle status with proper null checking
      if (json.containsKey('status') && json['status'] != null) {
        var statusValue = json['status'];
        if (statusValue is String) {
          status = statusValue.toLowerCase() == "active" ? 1 : 0;
        } else if (statusValue is int) {
          status = statusValue;
        } else {
          status = 1; // Default to active
        }
      } else {
        status = 1; // Default to active if key doesn't exist
      }

      // ✅ Optional fields
      title = json.containsKey('title') ? json['title'] : null;
      description =
          json.containsKey('description') ? json['description'] : null;

      // ✅ Handle location
      if (json.containsKey('location') && json['location'] != null) {
        var locationValue = json['location'];
        if (locationValue is String) {
          location = locationValue.toLowerCase() == 'all'
              ? 'All Locations'
              : locationValue;
        } else {
          location = locationValue.toString();
        }
      }

      // ✅ CRITICAL FIX: Handle active with proper null checking and default
      if (json.containsKey('active') && json['active'] != null) {
        var activeValue = json['active'];
        if (activeValue is int) {
          active = activeValue;
        } else if (activeValue is String) {
          active =
              int.tryParse(activeValue) ?? 1; // Default to 1 if parse fails
        } else if (activeValue is bool) {
          active = activeValue ? 1 : 0;
        } else {
          active = 1; // Default to active
        }
      } else {
        active = 1; // ✅ Default to active if key doesn't exist or is null
      }

      // ✅ Handle location_id
      if (json.containsKey('location_id') && json['location_id'] != null) {
        var locationIdValue = json['location_id'];
        if (locationIdValue is String) {
          locationId = int.tryParse(locationIdValue);
        } else if (locationIdValue is int) {
          locationId = locationIdValue;
        }
      }

      // ✅ Handle dates with proper null checking
      if (json.containsKey('created_at') && json['created_at'] != null) {
        createdAt = json['created_at'].toString();
      }

      if (json.containsKey('updated_at') && json['updated_at'] != null) {
        updatedAt = json['updated_at'].toString();
      }

      // ✅ Handle assigned
      if (json.containsKey('assigned') && json['assigned'] != null) {
        var assignedValue = json['assigned'];
        if (assignedValue is Map<String, dynamic>) {
          try {
            assigned = Assigned.fromJson(assignedValue);
          } catch (e) {
            if (kDebugMode) {
              logger.d("⚠️ Error parsing assigned: $e");
            }
            assigned = null;
          }
        }
      }

      // ✅ Handle requireEv
      if (json.containsKey('require_ev') && json['require_ev'] != null) {
        var requireEvValue = json['require_ev'];
        if (requireEvValue is String) {
          requireEv = int.tryParse(requireEvValue);
        } else if (requireEvValue is int) {
          requireEv = requireEvValue;
        }
      }
    } catch (e, stackTrace) {
      if (kDebugMode) {
        logger.d("❌ Error parsing User JSON: $e");
      }
      if (kDebugMode) {
        logger.d("📍 Stack trace: $stackTrace");
      }
      if (kDebugMode) {
        logger.d("📦 Problematic JSON: $json");
      }

      // ✅ Set safe defaults to prevent null errors
      id = 0;
      firstName = 'Unknown';
      lastName = 'User';
      email = '';
      status = 1;
      active = 1; // ✅ Default to active

      rethrow; // ✅ Rethrow to let caller handle error
    }
  }

  Map<String, dynamic> toJson() {
    final Map<String, dynamic> data = <String, dynamic>{};
    data['id'] = id;
    data['first_name'] = firstName;
    data['last_name'] = lastName;
    data['role'] = role;
    data['role_id'] = roleId;
    data['email'] = email;
    data['phone'] = phone;
    data['country_code'] = countryCode;
    data['password'] = password;
    data['password_confirmation'] = passwordConfirmation;
    data['type'] = type;
    data['dob'] = dob;
    data['doj'] = doj;
    data['address'] = address;
    data['city'] = city;
    data['state'] = state;
    data['country'] = country;
    data['zip'] = zip;
    data['profile'] = profile;
    // Convert int status to string for API (App: 1/0 -> API: "active"/"inactive")
    data['status'] = status == 1 ? "active" : "inactive";
    data['created_at'] = createdAt;
    data['updated_at'] = updatedAt;
    if (assigned != null) {
      data['assigned'] = assigned!.toJson();
    }
    data['require_ev'] = requireEv;
    data['avatar'] = avatar;
    data['title'] = title;
    data['description'] = description;
    data['location'] = location;
    data['active'] = active;
    data['location_id'] = locationId;
    if (profile != null &&
        profile!.isNotEmpty &&
        !profile!.startsWith('http') &&
        !profile!.startsWith('https')) {
      data['profile'] = profile;
    }

    return data;
  }

