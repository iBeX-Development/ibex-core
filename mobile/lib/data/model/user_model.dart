final logger = Logger();

class Autogenerated {
  bool? error;
  String? message;
  int? total;
  List<User>? data;

  Autogenerated({this.error, this.message, this.total, this.data});

  Autogenerated.fromJson(Map<String, dynamic> json) {
    error = json['error'];
    message = json['message'];
    total = json['total'] ?? 0; // Default to 0 if total is not provided
    if (json['data'] != null) {
      data = <User>[];
      json['data'].forEach((v) {
        data!.add(User.fromJson(v));
      });
    }
  }

  Map<String, dynamic> toJson() {
    final Map<String, dynamic> data = <String, dynamic>{};
    data['error'] = error;
    data['message'] = message;
    data['total'] = total;
    if (this.data != null) {
      data['data'] = this.data!.map((v) => v.toJson()).toList();
    }
    return data;
  }

  Autogenerated copyWith({
    bool? error,
    String? message,
    int? total,
    List<User>? data,
  }) {
    return Autogenerated(
      error: error ?? this.error,
      message: message ?? this.message,
      total: total ?? this.total,
      data: data ?? this.data,
    );
  }
}

