import 'package:flutter/foundation.dart';
import 'package:logger/logger.dart';
final logger = Logger();

class Autogenerated {
  bool? error;
  String? message;
  List<WorksTrade>? data;
  int? total;

  Autogenerated({this.error, this.message, this.data, this.total});

  Autogenerated.fromJson(Map<String, dynamic> json) {
    error = json['error'];
    message = json['message'];
    if (json['data'] != null) {
      data = <WorksTrade>[];
      json['data'].forEach((v) {
        data!.add(new WorksTrade.fromJson(v));
      });
    }
    total = json['total'];
  }

  Map<String, dynamic> toJson() {
    final Map<String, dynamic> data = new Map<String, dynamic>();
    data['error'] = this.error;
    data['message'] = this.message;
    if (this.data != null) {
      data['data'] = this.data!.map((v) => v.toJson()).toList();
    }
    data['total'] = this.total;
    return data;
  }
}

class WorksTrade {
  int? id;
  String? title;
  String? status;
  int? progress;
  String? cost;
  String? startDate;
  String? endDate;
  String? createdBy;
  String? description;
  String? createdAt;
  String? updatedAt;

  String? amount;
  String? actualQuantity;
  String? quantity;
  String? actualPrice;
  String? actualAmount;

  // ✅ Trade nested object (not parts!)
  int? tradeId;
  String? tradeName;
  String? tradeCode;
  String? tradeDescription;
  String? tradeRate;
  String? tradeStatus;
  int? tradeActive;

  WorksTrade({
    this.id,
    this.title,
    this.status,
    this.progress,
    this.cost,
    this.startDate,
    this.endDate,
    this.createdBy,
    this.description,
    this.createdAt,
    this.updatedAt,
    this.amount,
    this.quantity,
    this.actualQuantity,
    this.actualPrice,
    this.actualAmount,
    this.tradeId,
    this.tradeName,
    this.tradeCode,
    this.tradeDescription,
    this.tradeRate,
    this.tradeStatus,
    this.tradeActive,
  });

  WorksTrade.fromJson(Map<String, dynamic> json) {
    try {
      id = json['id'];
      status = json['status']?.toString();
      progress = json['progress'];

      // ✅ Safe conversion for amounts (always convert to String)
      // amount = json['amount'] is String
      //     ? int.tryParse(json['amount'])
      //     : json['amount'];
      // Work order level fields
      // ✅ Safe int/String conversion for quantities

      cost = json['rate']?.toString();
      quantity = json['duration']?.toString();
      actualQuantity = json['actual_duration']?.toString();
      amount = json['total']?.toString();
      actualAmount = json['actual_total']?.toString();

      actualPrice =
          json['actual_rate']?.toString(); // Convert any type to String

      // ✅ Dates
      startDate = json['start_date'];
      endDate = json['end_date'];
      // ✅ Progress
      progress = json['progress'] is String
          ? int.tryParse(json['progress'])
          : json['progress'];

      startDate = json['created_at'] ?? '';
      endDate = json['end_date'] ?? '';
      createdBy = json['created_by'] ?? '';
      createdAt = json['created_at'] ?? '';
      updatedAt = json['updated_at'] ?? '';

      // ✅ Parse nested trade object (not parts!)
      if (json['trade'] != null && json['trade'] is Map) {
        final tradeData = json['trade'] as Map<String, dynamic>;

        tradeId = tradeData['id'];
        tradeStatus = tradeData['status']?.toString();
        tradeName = tradeData['name'] ?? '';
        tradeCode = tradeData['code'] ?? '';
        tradeDescription = tradeData['description'] ?? '';
        tradeRate = tradeData['rate']?.toString();
        tradeActive = tradeData['active'];

        // ✅ Use trade name as title if title is empty
        title = tradeName;

        // ✅ Use trade description if description is empty
        description = tradeDescription;
      }
    } catch (e, stackTrace) {
      if (kDebugMode) {
        logger.d('❌ Error parsing WorksTrade: $e');
      }
      if (kDebugMode) {
        logger.d('❌ Stack trace: $stackTrace');
      }
    }
  }

  // ✅ Progress helpers
  double get progressPercentage {
    if (progress == null || progress! <= 0) return 0.0;
    if (progress! >= 100) return 1.0;
    return progress! / 100.0;
  }

  String get progressText => "${progress ?? 0}%";
  bool get hasProgress => progress != null && progress! > 0;

  // ✅ Status helpers
  bool get isActive => status == '1' || status?.toLowerCase() == 'active';
  bool get isCompleted => status == '2' || status?.toLowerCase() == 'completed';
  bool get isPending => status == '0' || status?.toLowerCase() == 'pending';

// ✅ Helper getters
  String get displayName => tradeName ?? 'Untitled Trade';
  String get displayDescription => tradeDescription ?? '';
  String get displayPrice =>
      cost ??
      tradeRate ??
      '0'; // Use planned rate (cost) first, fallback to base trade rate
  String get displayAmount => amount?.toString() ?? '0';
  String get displayActualAmount => actualAmount ?? '0';
  String get displayActualPrice => actualPrice ?? '0';

  // ✅ Formatted price helpers
  String get formattedPrice {
    try {
      final price = double.tryParse(displayPrice.replaceAll(',', '')) ?? 0.0;
      return _formatNumber(price);
    } catch (e) {
      return displayPrice;
    }
  }

  String get formattedAmount {
    try {
      final amt = double.tryParse(displayAmount.replaceAll(',', '')) ?? 0.0;
      return _formatNumber(amt);
    } catch (e) {
      return displayAmount;
    }
  }

  String get formattedActualAmount {
    try {
      final amt =
          double.tryParse(displayActualAmount.replaceAll(',', '')) ?? 0.0;
      return _formatNumber(amt);
    } catch (e) {
      return displayActualAmount;
    }
  }

  String get formattedActualPrice {
    try {
      final price =
          double.tryParse(displayActualPrice.replaceAll(',', '')) ?? 0.0;
      return _formatNumber(price);
    } catch (e) {
      return displayActualPrice;
    }
  }

  // ✅ Helper method for number formatting
  String _formatNumber(double number) {
    return number.toStringAsFixed(0).replaceAllMapped(
          RegExp(r'(\d{1,3})(?=(\d{3})+(?!\d))'),
          (Match m) => '${m[1]},',
        );
  }

  Map<String, dynamic> toJson() {
    final Map<String, dynamic> data = <String, dynamic>{};
    data['id'] = id;
    data['status'] = status;
    data['progress'] = progress;

    // ✅ Planned values (quantity, price, amount = duration, rate, total)
    data['duration'] = quantity; // duration
    data['rate'] = cost; // rate
    data['total'] = amount; // total

    // ✅ Actual values
    data['actual_duration'] = actualQuantity;
    data['actual_rate'] = actualPrice;
    data['actual_total'] = actualAmount;

    if (tradeId != null) {
      data['trade'] = {
        'id': tradeId,
        'status': tradeStatus,
        'name': tradeName,
        'code': tradeCode,
        'description': tradeDescription,
        'rate': tradeRate,
        'active': tradeActive,
      };
    }

    return data;
  }
}
