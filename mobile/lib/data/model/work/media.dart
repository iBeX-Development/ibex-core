import 'package:flutter/foundation.dart';
import 'package:ibex/config/constants.dart';
import 'package:logger/logger.dart';

final logger = Logger();

class Autogenerated {
  bool? error;
  String? message;
  List<MediaModel>? data;
  int? total;

  Autogenerated({this.error, this.message, this.data, this.total});

  Autogenerated.fromJson(Map<String, dynamic> json) {
    error = json['error'];
    message = json['message'];
    if (json['data'] != null) {
      data = <MediaModel>[];
      json['data'].forEach((v) {
        data!.add(new MediaModel.fromJson(v));
      });
    }
    total = json['total'];
  }

  Map<String, dynamic> toJson() {
    final Map<String, dynamic> data = new Map<String, dynamic>();
    data['error'] = this.error;
    data['message'] = this.message;
    if (this.data != null) {
      data['data'] = this.data!.map((v) => v.toJson()).toList();
    }
    data['total'] = this.total;
    return data;
  }
}

class MediaModel {
  int? id;
  int? workOrder;
  String? status;

  // ✅ Nested file object
  MediaFile? file;

  // Legacy fields (for backward compatibility)
  String? preview;
  String? fileName;
  String? fileSize;
  String? createdAt;
  String? updatedAt;
  bool? canDelete;

  MediaModel({
    this.id,
    this.workOrder,
    this.status,
    this.file,
    this.preview,
    this.fileName,
    this.fileSize,
    this.createdAt,
    this.updatedAt,
    this.canDelete,
  });

  MediaModel.fromJson(Map<String, dynamic> json) {
    try {
      id = json['id'];
      workOrder = json['work_order'];
      status = json['status']?.toString();

      // ✅ Parse nested file object
      if (json['file'] != null && json['file'] is Map) {
        file = MediaFile.fromJson(json['file']);
      }

      // Legacy fields (for backward compatibility)
      preview = json['preview'] ?? file?.fileUrl;
      fileName = json['file_name'] ?? file?.filenameDownload;
      fileSize = json['file_size'] ?? file?.filesize;
      createdAt = json['created_at'] ?? file?.createdOn;
      updatedAt = json['updated_at'] ?? file?.modifiedOn;
      canDelete = json['can_delete'];
    } catch (e, stackTrace) {
      if (kDebugMode) {
        logger.d('❌ Error parsing MediaModel: $e');
      }
      if (kDebugMode) {
        logger.d('❌ Stack trace: $stackTrace');
      }
      if (kDebugMode) {
        logger.d('❌ Problematic JSON: $json');
      }
    }
  }

  Map<String, dynamic> toJson() {
    final Map<String, dynamic> data = <String, dynamic>{};
    data['id'] = id;
    data['work_order'] = workOrder;
    data['status'] = status;

    if (file != null) {
      data['file'] = file!.toJson();
    }

    // Legacy fields
    data['preview'] = preview;
    data['file_name'] = fileName;
    data['file_size'] = fileSize;
    data['created_at'] = createdAt;
    data['updated_at'] = updatedAt;
    data['can_delete'] = canDelete;

    return data;
  }

  // ✅ Helper getters
  String get downloadUrl => file?.downloadUrl ?? file?.fileUrl ?? '';
  String get displayFileName => file?.filenameDownload ?? fileName ?? 'unknown';
  String get displayFileSize => file?.formattedFileSize ?? fileSize ?? '0';
  String get displayFileUrl => file?.fileUrl ?? preview ?? '';
  String get displayFileType => file?.type ?? '';
  String get displayTitle => file?.title ?? displayFileName;
  bool get isImage => displayFileType.startsWith('image/');
  bool get isVideo => displayFileType.startsWith('video/');
  bool get isPdf => displayFileType == 'application/pdf';
  int? get width => file?.width;
  int? get height => file?.height;

  // ✅ Add validation getter
  bool get canDownload => downloadUrl.isNotEmpty && file?.id != null;

  // ✅ Helper method for downloading
  Map<String, String> get downloadInfo => {
        'url': downloadUrl,
        'fileName': displayFileName,
        'fileSize': displayFileSize,
        'fileType': displayFileType,
      };
}

// ✅ New class for nested file object
class MediaFile {
  String? id;
  String? storage;
  String? filenameDisk;
  String? filenameDownload;
  String? title;
  String? type;
  String? folder;
  String? uploadedBy;
  String? createdOn;
  String? modifiedBy;
  String? modifiedOn;
  String? charset;
  String? filesize;
  int? width;
  int? height;
  int? duration;
  String? embed;
  String? description;
  String? location;
  String? tags;
  Map<String, dynamic>? metadata;
  int? focalPointX;
  int? focalPointY;
  String? tusId;
  Map<String, dynamic>? tusData;
  String? uploadedOn;

  MediaFile({
    this.id,
    this.storage,
    this.filenameDisk,
    this.filenameDownload,
    this.title,
    this.type,
    this.folder,
    this.uploadedBy,
    this.createdOn,
    this.modifiedBy,
    this.modifiedOn,
    this.charset,
    this.filesize,
    this.width,
    this.height,
    this.duration,
    this.embed,
    this.description,
    this.location,
    this.tags,
    this.metadata,
    this.focalPointX,
    this.focalPointY,
    this.tusId,
    this.tusData,
    this.uploadedOn,
  });

  MediaFile.fromJson(Map<String, dynamic> json) {
    try {
      id = json['id'];
      storage = json['storage'];
      filenameDisk = json['filename_disk'];
      filenameDownload = json['filename_download'];
      title = json['title'];
      type = json['type'];
      folder = json['folder'];
      uploadedBy = json['uploaded_by'];
      createdOn = json['created_on'];
      modifiedBy = json['modified_by'];
      modifiedOn = json['modified_on'];
      charset = json['charset'];
      filesize = json['filesize'];
      width = json['width'];
      height = json['height'];
      duration = json['duration'];
      embed = json['embed'];
      description = json['description'];
      location = json['location'];
      tags = json['tags'];

      if (json['metadata'] != null && json['metadata'] is Map) {
        metadata = Map<String, dynamic>.from(json['metadata']);
      }

      focalPointX = json['focal_point_x'];
      focalPointY = json['focal_point_y'];
      tusId = json['tus_id'];

      if (json['tus_data'] != null && json['tus_data'] is Map) {
        tusData = Map<String, dynamic>.from(json['tus_data']);
      }

      uploadedOn = json['uploaded_on'];
    } catch (e) {
      if (kDebugMode) {
        logger.d('❌ Error parsing MediaFile: $e');
      }
    }
  }

  Map<String, dynamic> toJson() {
    final Map<String, dynamic> data = <String, dynamic>{};
    data['id'] = id;
    data['storage'] = storage;
    data['filename_disk'] = filenameDisk;
    data['filename_download'] = filenameDownload;
    data['title'] = title;
    data['type'] = type;
    data['folder'] = folder;
    data['uploaded_by'] = uploadedBy;
    data['created_on'] = createdOn;
    data['modified_by'] = modifiedBy;
    data['modified_on'] = modifiedOn;
    data['charset'] = charset;
    data['filesize'] = filesize;
    data['width'] = width;
    data['height'] = height;
    data['duration'] = duration;
    data['embed'] = embed;
    data['description'] = description;
    data['location'] = location;
    data['tags'] = tags;
    data['metadata'] = metadata;
    data['focal_point_x'] = focalPointX;
    data['focal_point_y'] = focalPointY;
    data['tus_id'] = tusId;
    data['tus_data'] = tusData;
    data['uploaded_on'] = uploadedOn;
    return data;
  }

  // ✅ Helper getters
  String get fileUrl {
    // Construct file URL based on your API base URL
    if (id != null && id!.isNotEmpty) {
      return '${baseUrl}assets/$id';
    }
    return '';
  }

  String get downloadUrl {
    if (id != null && id!.isNotEmpty) {
      return '${baseUrl}assets/$id?download';
    }
    return '';
  }

  String get thumbnailUrl {
    if (id != null && type?.startsWith('image/') == true) {
      return '${baseUrl}assets/$id?fit=cover&width=300&height=300&quality=80';
    }
    return fileUrl;
  }

  String get formattedFileSize {
    if (filesize == null) return '0 B';

    try {
      final bytes = int.parse(filesize!);
      if (bytes < 1024) return '$bytes B';
      if (bytes < 1024 * 1024) return '${(bytes / 1024).toStringAsFixed(1)} KB';
      if (bytes < 1024 * 1024 * 1024)
        return '${(bytes / (1024 * 1024)).toStringAsFixed(1)} MB';
      return '${(bytes / (1024 * 1024 * 1024)).toStringAsFixed(1)} GB';
    } catch (e) {
      return filesize ?? '0 B';
    }
  }

  String get displayDimensions {
    if (width != null && height != null) {
      return '${width}x$height';
    }
    return '';
  }

  String get formattedDuration {
    if (duration == null) return '';

    final seconds = duration!;
    final hours = seconds ~/ 3600;
    final minutes = (seconds % 3600) ~/ 60;
    final secs = seconds % 60;

    if (hours > 0) {
      return '$hours:${minutes.toString().padLeft(2, '0')}:${secs.toString().padLeft(2, '0')}';
    } else {
      return '$minutes:${secs.toString().padLeft(2, '0')}';
    }
  }
}
