import 'package:flutter/foundation.dart';
import 'package:logger/logger.dart';
final logger = Logger();

class Autogenerated {
  bool? error;
  String? message;
  List<InspectionsTrade>? data;
  int? total;

  Autogenerated({this.error, this.message, this.data, this.total});

  Autogenerated.fromJson(Map<String, dynamic> json) {
    error = json['error'];
    message = json['message'];
    if (json['data'] != null) {
      data = <InspectionsTrade>[];
      json['data'].forEach((v) {
        data!.add(new InspectionsTrade.fromJson(v));
      });
    }
    total = json['total'];
  }

  Map<String, dynamic> toJson() {
    final Map<String, dynamic> data = new Map<String, dynamic>();
    data['error'] = this.error;
    data['message'] = this.message;
    if (this.data != null) {
      data['data'] = this.data!.map((v) => v.toJson()).toList();
    }
    data['total'] = this.total;
    return data;
  }
}

class InspectionsTrade {
  int? id;
  String? title;
  String? status;
  int? progress;
  String? cost;
  String? startDate;
  String? endDate;
  String? createdBy;
  String? description;
  String? createdAt;
  String? updatedAt;

  String? amount;
  String? actualQuantity;
  String? quantity;
  String? actualPrice;
  String? actualAmount;

  // ✅ Trades nested object
  int? partId;
  String? partName;
  String? partNumber;
  String? partDescription;
  String? partPrice;
  String? partSupplier;
  String? partMongolianName;
  String? partModelNo;
  String? partSerialNo;
  String? partMaterial;
  String? partTechnicalData;
  String? partPicture;
  String? partStatus;

  InspectionsTrade({
    this.id,
    this.title,
    this.status,
    this.progress,
    this.cost,
    this.startDate,
    this.endDate,
    this.createdBy,
    this.description,
    this.createdAt,
    this.updatedAt,
    this.amount,
    this.quantity,
    this.actualQuantity,
    this.actualPrice,
    this.actualAmount,
    this.partId,
    this.partName,
    this.partNumber,
    this.partDescription,
    this.partPrice,
    this.partSupplier,
    this.partMongolianName,
    this.partModelNo,
    this.partSerialNo,
    this.partMaterial,
    this.partTechnicalData,
    this.partPicture,
    this.partStatus,
  });

  InspectionsTrade.fromJson(Map<String, dynamic> json) {
    try {
      id = json['id'];
      status = json['status']?.toString();
      progress = json['progress'];

      // ✅ Safe conversion for amounts (always convert to String)
      // amount = json['amount'] is String
      //     ? int.tryParse(json['amount'])
      //     : json['amount'];
      // Inspection order level fields
      // ✅ Safe int/String conversion for quantities

      cost = json['price']?.toString();
      quantity = json['quantity']?.toString();
      actualQuantity = json['actual_quantity']?.toString();
      amount = json['amount']?.toString();
      actualAmount = json['actual_amount']?.toString();

      actualPrice = json['actual_price']
          ?.toString(); // Convert any type to String

      // ✅ Dates
      startDate = json['start_date'];
      endDate = json['end_date'];
      // ✅ Progress
      progress = json['progress'] is String
          ? int.tryParse(json['progress'])
          : json['progress'];

      startDate = json['date_created'] ?? '';
      endDate = json['end_date'] ?? '';
      createdBy = json['created_by'] ?? '';
      createdAt = json['date_created'] ?? '';
      updatedAt = json['updated_at'] ?? '';

      // ✅ Parse nested parts object
      if (json['parts'] != null && json['parts'] is Map) {
        final partsData = json['parts'] as Map<String, dynamic>;

        partId = partsData['id'];
        partStatus = partsData['status']?.toString();
        partName = partsData['name'] ?? '';
        partNumber = partsData['part_number'] ?? '';
        partDescription = partsData['description'] ?? '';
        partPrice = partsData['price']?.toString();
        partSupplier = partsData['supplier']?.toString();
        partMongolianName = partsData['mongolian_name'] ?? '';
        partModelNo = partsData['model_no'] ?? '';
        partSerialNo = partsData['serial_no'] ?? '';
        partMaterial = partsData['material'] ?? '';
        partTechnicalData = partsData['technical_data'] ?? '';
        partPicture = partsData['picture']?.toString();

        // ✅ Use parts name as title if title is empty
        title = partName;

        // ✅ Use parts description if description is empty
        description = partDescription;
      }
    } catch (e, stackTrace) {
      if (kDebugMode) {
        logger.d('❌ Error parsing InspectionsTrade: $e');
      }
      if (kDebugMode) {
        logger.d('❌ Stack trace: $stackTrace');
      }
    }
  }

  // ✅ Progress helpers
  double get progressPercentage {
    if (progress == null || progress! <= 0) return 0.0;
    if (progress! >= 100) return 1.0;
    return progress! / 100.0;
  }

  String get progressText => "${progress ?? 0}%";
  bool get hasProgress => progress != null && progress! > 0;

  // ✅ Status helpers
  bool get isActive => status == '1' || status?.toLowerCase() == 'active';
  bool get isCompleted => status == '2' || status?.toLowerCase() == 'completed';
  bool get isPending => status == '0' || status?.toLowerCase() == 'pending';

  // ✅ Helper getters
  String get displayName => partName ?? 'Untitled Trade';
  String get displayDescription => partDescription ?? '';
  String get displayPrice => partPrice ?? '0';
  String get displayAmount => amount?.toString() ?? '0';
  String get displayActualAmount => actualAmount ?? '0';
  String get displayActualPrice => actualPrice ?? '0';

  // ✅ Formatted price helpers
  String get formattedPrice {
    try {
      final price = double.tryParse(displayPrice.replaceAll(',', '')) ?? 0.0;
      return _formatNumber(price);
    } catch (e) {
      return displayPrice;
    }
  }

  String get formattedAmount {
    try {
      final amt = double.tryParse(displayAmount.replaceAll(',', '')) ?? 0.0;
      return _formatNumber(amt);
    } catch (e) {
      return displayAmount;
    }
  }

  String get formattedActualAmount {
    try {
      final amt =
          double.tryParse(displayActualAmount.replaceAll(',', '')) ?? 0.0;
      return _formatNumber(amt);
    } catch (e) {
      return displayActualAmount;
    }
  }

  String get formattedActualPrice {
    try {
      final price =
          double.tryParse(displayActualPrice.replaceAll(',', '')) ?? 0.0;
      return _formatNumber(price);
    } catch (e) {
      return displayActualPrice;
    }
  }

  // ✅ Helper method for number formatting
  String _formatNumber(double number) {
    return number
        .toStringAsFixed(0)
        .replaceAllMapped(
          RegExp(r'(\d{1,3})(?=(\d{3})+(?!\d))'),
          (Match m) => '${m[1]},',
        );
  }

  Map<String, dynamic> toJson() {
    final Map<String, dynamic> data = <String, dynamic>{};
    data['id'] = id;
    data['status'] = status;
    data['progress'] = progress;
    data['quantity'] = quantity;
    data['amount'] = amount;
    data['price'] = cost;
    data['actual_quantity'] = actualQuantity;
    data['actual_price'] = actualPrice;
    data['actual_amount'] = actualAmount;

    if (partId != null) {
      data['parts'] = {
        'id': partId,
        'status': partStatus,
        'name': partName,
        'part_number': partNumber,
        'description': partDescription,
        'price': partPrice,
        'supplier': partSupplier,
        'mongolian_name': partMongolianName,
        'model_no': partModelNo,
        'serial_no': partSerialNo,
        'material': partMaterial,
        'technical_data': partTechnicalData,
        'picture': partPicture,
      };
    }

    return data;
  }
}
