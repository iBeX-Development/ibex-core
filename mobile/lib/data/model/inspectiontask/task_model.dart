  InspectionTasks.fromJson(Map<String, dynamic> json) {
    // ✅ Basic fields
    id = json['id'];
    title = json['name'] ?? json['title'] ?? '';

    // ✅ Description - multiple possible fields
    description = json['description'] ??
        json['history_description'] ??
        json['request_info'] ??
        '';

    // ✅ Request info - important for work requests
    requestInfo = json['request_info'] ?? '';

    // ✅ Parent task ID
    parent = json['parent'] is int
        ? json['parent'] as int
        : (json['parent'] is String
            ? int.tryParse(json['parent'] as String) ?? 0
            : 0);

    // ✅ Status - handle both 'status' and 'wo_status'
    if (json['status'] is int) {
      statusId = json['status'] as int;
    } else if (json['wo_status'] is int) {
      statusId = json['wo_status'] as int;
    } else if (json['status'] is String) {
      statusId = int.tryParse(json['status'] as String) ?? 0;
    } else {
      statusId = 0;
    }

    // ✅ Status name/label
    status = json['status_name'] ?? '';

    // ✅ Task value
    taskValue = json['value'] != null ? json['value']?.toString() : null;

    // ✅ Template type
    if (json['template_type'] is int) {
      template_type = json['template_type'] as int;
    } else if (json['template_type'] is String) {
      template_type = int.tryParse(json['template_type'] as String) ?? 0;
    } else {
      template_type = 0;
    }

    // ✅ Priority - handle nullable and multiple formats
    if (json['priority'] is int) {
      priorityId = json['priority'] as int;
    } else if (json['priority'] is String) {
      priorityId = int.tryParse(json['priority'] as String) ?? 0;
    } else {
      priorityId = 0; // null case
    }

    // ✅ Priority name/label
    priority = json['priority_name'] ?? '';

    // ✅ Project/Inspectionorder ID - multiple possible field names
    if (json['workorder'] is int) {
      projectId = json['workorder'] as int;
    } else if (json['workorder'] is String) {
      projectId = int.tryParse(json['workorder'] as String) ?? 0;
    } else {
      projectId = 0;
    }

    // ✅ Inspectionspace ID
    workspaceId = json['workspace_id'] ?? 0;

    // ✅ Active status
    if (json['active'] is int) {
      // Store active status if needed (add field to model)
      // active = json['active'];
    }

    // ✅ Code field (if needed)
    // code = json['code'];

    // ✅ Created type
    // createdType = json['created_type'] ?? '';

    // ✅ Position
    // pos = json['pos'];

    // ✅ Update keys
    // updateKeys = json['update_keys'];

    // ✅ Children tasks parsing - handle nested structure
    if (json['children'] != null && json['children'] is List) {
      try {
        children = (json['children'] as List)
            .where((item) => item is Map<String, dynamic>)
            .map((childJson) =>
                InspectionTasks.fromJson(childJson as Map<String, dynamic>))
            .toList();
      } catch (e) {
        if (kDebugMode) {
          logger.d('⚠️ Error parsing children: $e');
        }
        children = [];
      }
    } else {
      children = [];
    }

    // ✅ Date parsing with null safety
    createdAt = DateParser.parse(json['created_at'] ?? json['date_created'])
        ?.toIso8601String();

    updatedAt = DateParser.parse(json[
                'update_at'] ?? // ← Note: API uses 'update_at' not 'updated_at'
            json['updated_at'] ??
            json['date_updated'] ??
            json['modified_at'])
        ?.toIso8601String();

    // ✅ Start and due dates
    startDate = DateParser.parse(json['start_date'] ?? json['started_at'])
        ?.toIso8601String();

    dueDate =
        DateParser.parse(json['due_date'] ?? json['due'])?.toIso8601String();

    // ✅ Created user and updated user (UUID strings)
    // createdUser = json['created_user'];
    // updatedUser = json['updated_user'];

    // ✅ Users parsing
    if (json['users'] != null && json['users'] is List) {
      users = <InspectionTaskUsers>[];
      for (var v in (json['users'] as List)) {
        if (v is Map<String, dynamic>) {
          users!.add(InspectionTaskUsers.fromJson(v));
        }
      }
    } else {
      users = [];
    }

    // ✅ User IDs
    if (json['user_id'] != null && json['user_id'] is List) {
      userId = (json['user_id'] as List)
          .map((e) => e is int ? e : int.tryParse(e.toString()) ?? 0)
          .toList();
    } else {
      userId = [];
    }

    // ✅ Clients parsing
    if (json['clients'] != null && json['clients'] is List) {
      clients = <InspectionTaskClients>[];
      for (var v in (json['clients'] as List)) {
        if (v is Map<String, dynamic>) {
          clients!.add(InspectionTaskClients.fromJson(v));
        }
      }
    } else {
      clients = [];
    }

    // ✅ Project name
    project = json['project'] ?? '';

    // ✅ Note - handle both formats
    note = json['note'] ?? json['safety_notes'] ?? '';

    // ✅ Favorite, pinned, client discuss flags
    favorite = json['favorite'] ?? 0;
    pinned = json['pinned'] ?? 0;
    clientCanDiscuss =
        json['client_can_discuss'] ?? json['can_client_discuss'] ?? 0;

    // ✅ Reminder settings
    enableReminder = json['enable_reminder'] ?? 0;
    lastReminderSent = json['last_reminder_sent'] ?? '';
    frequencyType = json['frequency_type'] ?? '';
    dayOfWeek = json['day_of_week'] ?? 0;
    dayOfMonth = json['day_of_month'] ?? 0;
    timeOfDay = json['time_of_day'] ?? '';

    // ✅ Recurring task settings
    enableRecurringTask = json['enable_recurring_task'] ?? 0;
    recurrenceFrequency = json['recurrence_frequency'] ?? '';
    recurrenceDayOfWeek = json['recurrence_day_of_week'] ?? 0;
    recurrenceDayOfMonth = json['recurrence_day_of_month'] ?? 0;
    recurrenceMonthOfYear = json['recurrence_month_of_year'] ?? 0;
    recurrenceStartsFrom = json['recurrence_starts_from'] ?? '';

    // ✅ Recurrence occurrences - handle int or string
    if (json['recurrence_occurrences'] is int) {
      recurrenceOccurrences = json['recurrence_occurrences'];
    } else if (json['recurrence_occurrences'] is String) {
      recurrenceOccurrences = int.tryParse(json['recurrence_occurrences']) ?? 0;
    } else {
      recurrenceOccurrences = 0;
    }

    completedOccurrences = json['completed_occurrences'] ?? 0;

    // ✅ Billing and completion
    createType = json['billing_type'] ?? '';
    completionPercentage =
        json['completion_percentage'] ?? json['wo_percent'] ?? 0;

    // ✅ Task list IDs
    if (json['task_list_id'] != null && json['task_list_id'] is List) {
      taskListId = (json['task_list_id'] as List)
          .map((e) => e is int ? e : int.tryParse(e.toString()) ?? 0)
          .toList();
    } else {
      taskListId = [];
    }

    // ✅ Custom fields parsing
    if (json['customFields'] != null && json['customFields'] is List) {
      customFields = <CustomFieldsInspectionTask>[];
      for (var v in json['customFields']) {
        if (v is Map<String, dynamic>) {
          customFields!.add(CustomFieldsInspectionTask.fromJson(v));
        }
      }
    } else {
      customFields = [];
    }

    // ✅ Custom field values parsing
    if (json['customFieldValues'] != null) {
      if (json['customFieldValues'] is Map<String, dynamic>) {
        customFieldValues =
            CustomFieldValuesInspectionTask.fromJson(json['customFieldValues']);
      } else if (json['customFieldValues'] is List) {
        var list = json['customFieldValues'] as List;
        if (list.isNotEmpty && list.first is Map<String, dynamic>) {
          customFieldValues = CustomFieldValuesInspectionTask.fromJson(
              list.first as Map<String, dynamic>);
        } else {
          customFieldValues = CustomFieldValuesInspectionTask(values: {});
        }
      } else {
        customFieldValues = CustomFieldValuesInspectionTask(values: {});
      }
    } else {
      customFieldValues = null;
    }
  }
