class CustomFieldsInspectionTask {
  int? id;
  String? module;
  String? fieldLabel;
  String? name;
  String? fieldType;
  String? guideText;
  List<String>? options;
  String? required;
  String? visibility;
  String? createdAt;
  String? updatedAt;

  CustomFieldsInspectionTask(
      {this.id,
      this.module,
      this.fieldLabel,
      this.name,
      this.fieldType,
      this.guideText,
      this.options,
      this.required,
      this.visibility,
      this.createdAt,
      this.updatedAt});

  CustomFieldsInspectionTask.fromJson(Map<String, dynamic> json) {
    id = json['id'];
    module = json['module'];
    fieldLabel = json['field_label'];
    name = json['name'];
    fieldType = json['field_type'];
    guideText = json['guide_text'];
    options =
        json['options'] != null ? (json['options'] as List).cast<String>() : [];
    required = json['required'];
    visibility = json['visibility'];
    createdAt = json['created_at'] ?? '';
    updatedAt = json['updated_at'] ?? '';
  }

  Map<String, dynamic> toJson() {
    final Map<String, dynamic> data = new Map<String, dynamic>();
    data['id'] = this.id;
    data['module'] = this.module;
    data['field_label'] = this.fieldLabel;
    data['name'] = this.name;
    data['field_type'] = this.fieldType;
    data['guide_text'] = this.guideText;
    data['options'] = this.options;
    data['required'] = this.required;
    data['visibility'] = this.visibility;
    data['created_at'] = this.createdAt;
    data['updated_at'] = this.updatedAt;
    return data;
  }
}

