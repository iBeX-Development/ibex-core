    data['recurrence_month_of_year'] = recurrenceMonthOfYear;
    data['recurrence_starts_from'] = recurrenceStartsFrom;
    data['recurrence_occurrences'] = recurrenceOccurrences;
    data['completed_occurrences'] = completedOccurrences;
    data['billing_type'] = createType;
    data['completion_percentage'] = completionPercentage;
    data['task_list_id'] = taskListId;
