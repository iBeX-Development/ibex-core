import 'package:flutter/foundation.dart';
import 'package:logger/logger.dart';
final logger = Logger();

class Autogenerated {
  bool? error;
  String? message;
  int? total;
  List<ActivityLog>? data;

  Autogenerated({this.error, this.message, this.total, this.data});

  Autogenerated.fromJson(Map<String, dynamic> json) {
    error = json['error'];
    message = json['message'];
    total = json['total'];
    if (json['data'] != null) {
      data = <ActivityLog>[];
      json['data'].forEach((v) {
        data!.add(ActivityLog.fromJson(v));
      });
    }
  }

  Map<String, dynamic> toJson() {
    final Map<String, dynamic> data = <String, dynamic>{};
    data['error'] = error;
    data['message'] = message;
    data['total'] = total;
    if (this.data != null) {
      data['data'] = this.data!.map((v) => v.toJson()).toList();
    }
    return data;
  }
}

class ActivityLog {
  int? id;
  String? userCreated;
  String? dateCreated;
  String? userUpdated;
  String? dateUpdated;
  int? woId;
  int? actionStatus;
  String? type;

  // ✅ Nested user objects
  ActivityUser? firstUser;
  ActivityUser? nextUser;

  // Legacy fields (for backward compatibility)
  int? actorId;
  String? actorName;
  String? actorType;
  int? typeId;
  int? workId;
  String? parentTypeId;
  String? parentType;
  String? actorProfile;
  String? typeTitle;
  String? parentTypeTitle;
  String? activity;
  String? message;
  String? createdAt;
  String? updatedAt;

  ActivityLog({
    this.id,
    this.userCreated,
    this.dateCreated,
    this.userUpdated,
    this.dateUpdated,
    this.woId,
    this.actionStatus,
    this.type,
    this.firstUser,
    this.nextUser,
    this.actorId,
    this.actorName,
    this.actorType,
    this.typeId,
    this.workId,
    this.parentTypeId,
    this.parentType,
    this.actorProfile,
    this.typeTitle,
    this.parentTypeTitle,
    this.activity,
    this.message,
    this.createdAt,
    this.updatedAt,
  });

  ActivityLog.fromJson(Map<String, dynamic> json) {
    try {
      id = json['id'];
      userCreated = json['user_created'];
      dateCreated = json['date_created'];
      userUpdated = json['user_updated'];
      dateUpdated = json['date_updated'];
      woId = json['wo_id'];
      actionStatus = json['action_status'];
      type = json['type'];

      // ✅ Parse nested first_user object
      if (json['first_user'] != null && json['first_user'] is Map) {
        firstUser = ActivityUser.fromJson(json['first_user']);
      }

      // ✅ Parse nested next_user object
      if (json['next_user'] != null && json['next_user'] is Map) {
        nextUser = ActivityUser.fromJson(json['next_user']);
      }

      // Legacy fields (for backward compatibility)
      actorId = json['actor_id'];
      actorName = json['actor_name'] ?? firstUser?.fullName;
      actorType = json['actor_type'];
      typeId = json['type_id'];
      workId = json['wo_id'];
      actorProfile = json['actor_profile'] ?? firstUser?.avatar;
      parentTypeId = json['parent_type_id'];
      parentType = json['parent_type'];
      typeTitle = json['type_title'];
      parentTypeTitle = json['parent_type_title'];
      activity = json['activity'];

      if (actionStatus == 1) {
        message = "$actorName created this #$workId";
      } else if (actionStatus == 2) {
        message = "$actorName approved this #$workId";
      } else if (actionStatus == 3) {
        message = "$actorName returned this #$workId";
      } else if (actionStatus == 4) {
        message = "$actorName assigned on this #$workId";
      } else if (actionStatus == 5) {
        message = "$actorName accepted work to this #$workId";
      } else if (actionStatus == 6) {
        message = "$actorName declined work to this #$workId";
      } else if (actionStatus == 6) {
        message = "$actorName declined work to this #$workId";
      } else if (actionStatus == 0) {
        message = "$actorName deleted this #$workId";
      } else {
        message = json['message'];
      }

      createdAt = json['created_at'] ?? json['date_created'];
      updatedAt = json['updated_at'] ?? json['date_updated'];

      // print(
      //     '🔥 Parsed ActivityLog: id=$id, firstUser=${firstUser?.fullName}, actionStatus=$actionStatus');
    } catch (e, stackTrace) {
      if (kDebugMode) {
        logger.d('❌ Error parsing ActivityLog: $e');
      }
      if (kDebugMode) {
        logger.d('❌ Stack trace: $stackTrace');
      }
      if (kDebugMode) {
        logger.d('❌ Problematic JSON: $json');
      }
    }
  }

  Map<String, dynamic> toJson() {
    final Map<String, dynamic> data = <String, dynamic>{};
    data['id'] = id;
    data['user_created'] = userCreated;
    data['date_created'] = dateCreated;
    data['user_updated'] = userUpdated;
    data['date_updated'] = dateUpdated;
    data['wo_id'] = woId;
    data['action_status'] = actionStatus;
    data['type'] = type;

    if (firstUser != null) {
      data['first_user'] = firstUser!.toJson();
    }

    if (nextUser != null) {
      data['next_user'] = nextUser!.toJson();
    }

    // Legacy fields
    data['actor_id'] = actorId;
    data['actor_name'] = actorName;
    data['actor_type'] = actorType;
    data['type_id'] = typeId;
    data['parent_type_id'] = parentTypeId;
    data['type'] = type;
    data['actor_profile'] = actorProfile;
    data['parent_type'] = parentType;
    data['type_title'] = typeTitle;
    data['parent_type_title'] = parentTypeTitle;
    data['activity'] = activity;
    data['message'] = message;
    data['created_at'] = createdAt;
    data['updated_at'] = updatedAt;

    return data;
  }

  // ✅ Helper getters
  String get displayName => firstUser?.fullName ?? actorName ?? 'Unknown';
  String get displayAvatar => firstUser?.avatar ?? actorProfile ?? '';
  String get displayEmail => firstUser?.email ?? '';
  String get displayDate => dateCreated ?? createdAt ?? '';
}

// ✅ New class for nested user objects
class ActivityUser {
  String? id;
  String? firstName;
  String? lastName;
  String? email;
  String? avatar;

  ActivityUser({
    this.id,
    this.firstName,
    this.lastName,
    this.email,
    this.avatar,
  });

  ActivityUser.fromJson(Map<String, dynamic> json) {
    try {
      id = json['id'];
      firstName = json['first_name'];
      lastName = json['last_name'];
      email = json['email'];
      avatar = json['avatar'];
    } catch (e) {
      if (kDebugMode) {
        logger.d('❌ Error parsing ActivityUser: $e');
      }
    }
  }

  Map<String, dynamic> toJson() {
    final Map<String, dynamic> data = <String, dynamic>{};
    data['id'] = id;
    data['first_name'] = firstName;
    data['last_name'] = lastName;
    data['email'] = email;
    data['avatar'] = avatar;
    return data;
  }

  // ✅ Helper getter for full name
  String get fullName {
    if (firstName != null && lastName != null) {
      return '$firstName $lastName';
    } else if (firstName != null) {
      return firstName!;
    } else if (lastName != null) {
      return lastName!;
    }
    return 'Unknown';
  }
}
